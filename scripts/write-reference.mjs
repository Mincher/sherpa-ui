#!/usr/bin/env node
/**
 * write-reference.mjs — the component reference: a Markdown page per component in
 * docs/components/, and an index, written from each spec and its example.
 * TRAP T-the-manifest-is-written-from-the-specs
 *
 *   npm run reference          write the pages; delete a generated page no spec makes
 *   npm run check:reference    fail when a page is not what the specs make
 *
 * Map:
 * - page — one component's page, from its spec and its example
 * - index — the index page: every component by category, with its first sentence
 * - pages — every page the specs make, path → text
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync, globSync, unlinkSync } from 'node:fs';
import { basename } from 'node:path';
import { specs, partsOf } from './write-manifest.mjs';
import { refToToken } from './lib/component-to-def.mjs';

const OUT = 'docs/components';
const BANNER = (from) => `<!-- GENERATED by scripts/write-reference.mjs from ${from}. Do not edit it: npm run reference. -->`;

/** A table cell: one line, its pipes escaped — inside code spans too, as GFM allows. */
const cell = (t) => String(t ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const code = (t) => (t === '' ? '`""`' : `\`${String(t).replace(/\|/g, '\\|')}\``);
/** Prose: outside a code span, a `<` is escaped and a known tag links to its page. */
const prose = (t, tags, self) => cell(t).split(/(`[^`]*`)/).map((seg, i) => (i % 2 ? seg
  : seg.replace(/</g, '&lt;').replace(/\bsherpa-[a-z][a-z0-9-]*[a-z0-9]\b/g,
    (m) => (tags.has(m) && m !== self ? `[${m}](${m}.md)` : m)))).join('');
const capital = (t) => (t ? t[0].toUpperCase() + t.slice(1) : '');
const table = (head, rows) => (rows.length
  ? [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n')
  : '');

/** A component's example, its markup joined. TRAP T-a-component-ships-its-example */
function example(tag) {
  const f = `src/components/${tag}/${tag}.example.json`;
  if (!existsSync(f)) return null;
  const e = JSON.parse(readFileSync(f, 'utf8'));
  return { ...e, html: [e.html].flat().join('') };
}

/** One component's page, from its spec and its example. */
export function page(s, ex, tags) {
  const tag = s.$name;
  // A `use` line names only components that exist.
  for (const m of String(ex?.use ?? '').replace(/`[^`]*`/g, '').matchAll(/\bsherpa-[a-z][a-z0-9-]*[a-z0-9]\b/g)) {
    if (!tags.has(m[0])) throw new Error(`${tag}.example.json: its use names ${m[0]}, which is no component`);
  }
  const say = (t) => prose(t, tags, tag);
  const ext = s.$extensions?.sherpa ?? {};
  const out = [BANNER(`${tag}.component.json and ${tag}.example.json`), '', `# ${tag}`, '', capital(say(s.$description)), ''];

  const facts = [];
  if (ext.category) facts.push(['Category', ext.category]);
  const root = s.element?.tag;
  if (root?.startsWith('sherpa-')) facts.push(['Wraps', tags.has(root) ? `[${root}](${root}.md)` : code(root)]);
  else if (root && s.element?.provides?.length) {
    facts.push(['Built on', `the native ${code(`<${root}>`)}, which gives ${s.element.provides.join(', ')}`]);
  }
  if ((s.templates ?? []).length > 1) facts.push(['Templates', s.templates.map(code).join(', ')]);
  if (ext.figmaName) facts.push(['Figma', cell(ext.figmaName)]);
  const dir = `../../src/components/${tag}`;
  facts.push(['Source', ['.ts', '.html', '.css', '.component.json', '.example.json']
    .map((f) => `[${f}](${dir}/${tag}${f})`).join(' · ')]);
  out.push(table(['', ''], facts), '');

  if (ex?.use) out.push('## When to use it', '', say(ex.use), '');
  if (ex) {
    // A whitespace-only text node is no slot content, so a newline between tags changes nothing.
    out.push('## Example', '', '```html', ex.html.replace(/>\s+</g, '>\n<'), '```', '');
    for (const f of ex.fill ?? []) out.push(`\`populate()\` is given, on ${code(f.at)}:`, '', '```json', JSON.stringify(f.data, null, 2), '```', '');
    if (ex.show) out.push(`${code(ex.show)} is opened with \`show()\`${ex.anchor ? `, against ${code(ex.anchor)}` : ''}.`, '');
  }

  const props = s.props ?? [];
  if (props.length) {
    out.push('## Attributes', '', table(['Attribute', 'Values', 'Default', 'What it does'], props.map((p) => [
      code(p.name),
      `${p.values?.length ? p.values.map(code).join(' ') : p.type === 'string' ? 'text' : p.type}${p.native ? ', native' : ''}`,
      p.default != null && p.default !== '' ? code(p.default) : '',
      say(p.description),
    ])), '');
  }
  const fields = ext.jsProps ?? [];
  if (fields.length) {
    out.push('## Properties', '', table(['Property', 'Type', 'Access', 'What it is'], fields.map((p) => [
      code(p.name), code(p.type ?? 'unknown'), p.access === 'read' ? 'read only' : 'read and write', say(p.description),
    ])), '');
  }
  const methods = ext.methods ?? [];
  if (methods.length) {
    out.push('## Methods', '', table(['Method', 'What it does'], methods.map((m) => [code(`${m.name}(${m.args ?? ''})`), say(m.description)])), '');
  }
  if ((ext.commands ?? []).length) {
    out.push('## Commands', '', "A button with `commandfor` set to this element's id sends these as its `command`:", '',
      table(['Command', 'Calls'], ext.commands.map((c) => [code(c.name), code(`${c.method}()`)])), '');
  }
  const events = s.events ?? [];
  if (events.length) {
    const said = events.some((e) => e.description || e.composed === false || e.cancelable);
    out.push('## Events', '', ...(events.every((e) => e.bubbles) ? ['Each one bubbles.', ''] : []),
      table(['Event', 'Detail', ...(said ? ['What it means'] : [])], events.map((e) => [
        code(e.name),
        e.detail && Object.keys(e.detail).length ? code(`{ ${Object.entries(e.detail).map(([k, t]) => `${k}: ${t}`).join('; ')} }`) : '',
        ...(said ? [[say(e.description), e.cancelable ? 'A host may call `preventDefault()` to take it over.' : '',
          e.composed === false ? 'It stops at the shadow root.' : ''].filter(Boolean).join(' ')] : []),
      ])), '');
  }
  const slots = s.slots ?? [];
  if (slots.length) {
    out.push('## Slots', '', table(['Slot', 'Accepts', 'What it holds'], slots.map((sl) => [
      sl.name ? code(sl.name) : '(default)', (sl.accepts ?? []).join(', '), say(sl.description),
    ])), '');
  }
  const parts = [...partsOf(s.anatomy)].sort();
  if (parts.length) out.push('## Parts', '', 'Style these from outside with `::part()`:', '', parts.map(code).join(', '), '');
  const toks = Object.entries(s.tokens ?? {});
  if (toks.length) {
    out.push('## CSS custom properties it reads', '', "What each class's base rule reads:", '',
      table(['Custom property', 'Class', 'Property'], toks.map(([k, ref]) => {
        const dot = k.indexOf('.');
        return [code(`--sherpa-${refToToken(ref)}`), code(`.${k.slice(0, dot)}`), code(k.slice(dot + 1))];
      })), '');
  }
  if (s.populate) out.push('## populate()', '', code(s.populate.shape), '', say(s.populate.description), '');
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

/** The index page: every component by category, with its first sentence. */
export function index(all, tags) {
  const groups = Object.groupBy(all, (s) => s.$extensions?.sherpa?.category ?? 'other');
  const uses = all.filter((s) => example(s.$name)?.use).length;
  const out = [BANNER('the component specs'), '', '# Components', '',
    `${all.length} components. Each page is written from the component's spec and its example. ${uses} of ${all.length} say when to use them.`, ''];
  const order = Object.keys(groups).sort((a, b) => (a === 'other') - (b === 'other') || (a < b ? -1 : a > b ? 1 : 0));
  for (const k of order) {
    const rows = groups[k].sort((a, b) => (a.$name < b.$name ? -1 : 1)).map((s) => [`[${s.$name}](${s.$name}.md)`,
      capital(prose(cell(s.$description).split(/(?<=\.)\s/)[0], tags, ''))]);
    out.push(`## ${capital(k)}`, '', table(['Component', 'What it is'], rows), '');
  }
  return `${out.join('\n').trimEnd()}\n`;
}

/** Every page the specs make, path → text. */
export function pages() {
  const all = specs();
  const tags = new Set(all.map((s) => s.$name));
  const out = new Map(all.map((s) => [`${OUT}/${s.$name}.md`, page(s, example(s.$name), tags)]));
  out.set(`${OUT}/README.md`, index(all, tags));
  return out;
}

const isMain = process.argv[1] && basename(process.argv[1]) === 'write-reference.mjs';
if (isMain) {
  const check = process.argv.includes('--check');
  const want = pages();
  const made = (f) => readFileSync(f, 'utf8').startsWith('<!-- GENERATED by scripts/write-reference.mjs');
  const orphans = globSync(`${OUT}/*.md`).filter((f) => !want.has(f));
  if (check) {
    const stale = [...want].filter(([f, text]) => !existsSync(f) || readFileSync(f, 'utf8') !== text).map(([f]) => f);
    if (stale.length || orphans.length) {
      console.error(`check:reference — not what the specs make: ${[...stale, ...orphans].join(', ')}. Run: npm run reference`);
      process.exit(1);
    }
    console.log(`check:reference — ${want.size} pages match`);
  } else {
    mkdirSync(OUT, { recursive: true });
    for (const [f, text] of want) writeFileSync(f, text);
    for (const f of orphans) if (made(f)) unlinkSync(f);
    console.log(`reference — ${want.size} pages written`);
  }
}
