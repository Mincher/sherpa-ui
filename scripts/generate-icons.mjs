#!/usr/bin/env node
/**
 * Build one module per icon, `src/core/ui/icons/<name>.ts`, and the list of
 * names, `src/core/ui/icon-names.ts`, from the SVGs in `src/icons/`. A page
 * loads an icon's module the first time it draws it. Will, TODO 199.
 *
 * Each entry carries the drawing's inner markup plus its INK bbox, so a viewBox
 * can be fitted to the art itself. An icon's 14x14 frame pads each drawing
 * differently — `triangle-down` inks 7x4.375 of its 14 box — so the frame
 * cannot size the art.
 *
 * The bbox needs a real SVG engine, so the drawings run through headless
 * Chromium once at build time. Nothing measures at runtime.
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync } from 'node:fs';
import { join, basename } from 'node:path';
import { chromium } from '@playwright/test';

const DIR = 'src/icons';
const OUT = 'src/core/ui/icons';
const NAMES = 'src/core/ui/icon-names.ts';

const files = readdirSync(DIR).filter((f) => f.endsWith('.svg')).sort();
if (files.length === 0) {
  console.error(`generate-icons: no .svg files in ${DIR}/`);
  process.exit(1);
}

const icons = [];
const skipped = [];
for (const file of files) {
  const src = readFileSync(join(DIR, file), 'utf8');
  const viewBox = /viewBox="([^"]+)"/.exec(src)?.[1];
  // The BODY, not a joined path list: a polychrome icon's paths carry different
  // fills, and `status-ok` is a green disc with a white tick knocked out of it.
  const body = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(src)?.[1]?.trim();
  if (!viewBox || !body) { skipped.push(`${file} (no viewBox or body)`); continue; }
  icons.push({ name: basename(file, '.svg'), viewBox, body });
}

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent('<div id="probe"></div>');
const measured = await page.evaluate((list) => {
  const host = document.getElementById('probe');
  const NS = 'http://www.w3.org/2000/svg';
  return list.map(({ name, viewBox, body }) => {
    const svg = document.createElementNS(NS, 'svg');
    svg.setAttribute('viewBox', viewBox);
    // The body is markup, so it must be parsed IN the SVG namespace — an
    // innerHTML on an SVG element does that; on an HTML one it would not.
    svg.innerHTML = body;
    host.appendChild(svg);
    // The union of every shape, which is the drawing's true extent.
    const b = svg.getBBox();
    host.replaceChildren();
    const r = (n) => Math.round(n * 1000) / 1000;
    return { name, ink: [r(b.x), r(b.y), r(b.width), r(b.height)], empty: b.width === 0 || b.height === 0 };
  });
}, icons);
await browser.close();

const inkByName = new Map(measured.map((m) => [m.name, m]));
const empty = measured.filter((m) => m.empty).map((m) => m.name);

const esc = (s) => s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

// The set is the folder: a module whose icon has gone goes with it.
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
for (const i of icons) {
  const { ink } = inkByName.get(i.name);
  const body = esc(i.body.replace(/\s*\n\s*/g, ''));
  writeFileSync(join(OUT, `${i.name}.ts`), `// GENERATED by scripts/generate-icons.mjs from src/icons/${i.name}.svg — do not edit.
import type { IconArt } from '../icon-names.js';

export default { body: \`${body}\`, frame: '${i.viewBox}', ink: [${ink.join(', ')}] } satisfies IconArt;
`);
}

writeFileSync(NAMES, `// GENERATED by scripts/generate-icons.mjs from src/icons/ — do not edit.
// The NAMES only: each icon's drawing is its own module, loaded the first time
// it is drawn. TRAP T-an-icon-loads-when-first-drawn
//
// Map:
// - IconArt — one icon: its drawing, the frame it is drawn in, and the ink bbox of the drawing
// - ICON_NAMES — every icon the set holds, by name

/** One icon: its drawing, the frame it is drawn in, and the ink bbox of the drawing. */
export interface IconArt {
  /** The SVG body — one or more shapes, with their own fills preserved. */
  readonly body: string;
  /** The icon's own frame, and the viewBox it is DRAWN against. TRAP T-icon-box-is-not-the-glyph */
  readonly frame: string;
  /** The drawing's bounding box: [x, y, width, height], in frame units. */
  readonly ink: readonly [number, number, number, number];
}

/** Every icon the set holds, by name. */
export const ICON_NAMES: ReadonlySet<string> = new Set([
${icons.map((i) => `  '${i.name}',`).join('\n')}
]);
`);

console.log(`generate-icons: ${icons.length} icons → ${OUT}/ and ${NAMES}`);
if (skipped.length) console.log(`  skipped: ${skipped.join(', ')}`);
if (empty.length) console.log(`  EMPTY (drew nothing): ${empty.join(', ')}`);
