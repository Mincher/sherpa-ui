#!/usr/bin/env node
/**
 * Build the icon sprite, `src/core/ui/icons.svg` — one `<symbol>` per icon, its
 * id the icon's name and its viewBox the icon's frame — and the list of names,
 * `src/core/ui/icon-names.ts`, from the SVGs in `src/icons/`.
 * TRAP T-an-icon-loads-when-first-drawn
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, basename } from 'node:path';

const DIR = 'src/icons';
const SPRITE = 'src/core/ui/icons.svg';
const NAMES = 'src/core/ui/icon-names.ts';

const files = readdirSync(DIR).filter((f) => f.endsWith('.svg')).sort();
if (files.length === 0) {
  console.error(`generate-icons: no .svg files in ${DIR}/`);
  process.exit(1);
}

const icons = [];
const bad = [];
for (const file of files) {
  const name = basename(file, '.svg');
  const src = readFileSync(join(DIR, file), 'utf8');
  const viewBox = /viewBox="([^"]+)"/.exec(src)?.[1];
  // The BODY, with each shape's own fill: `status-ok` is a green disc with a white tick knocked out.
  const body = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(src)?.[1]?.trim().replace(/\s*\n\s*/g, '');
  if (!/^[A-Za-z][\w-]*$/.test(name)) bad.push(`${file} (not a valid id)`);
  else if (!viewBox || !body) bad.push(`${file} (no viewBox or body)`);
  else if (!/<(path|circle|rect|ellipse|polygon|polyline|line)\b/.test(body)) bad.push(`${file} (draws nothing)`);
  // Every symbol shares one document: an id inside one would clash.
  else if (/\sid=/.test(body)) bad.push(`${file} (an id inside the drawing)`);
  else icons.push({ name, viewBox, body });
}
if (bad.length) {
  console.error(`generate-icons: ${bad.join(', ')}`);
  process.exit(1);
}

writeFileSync(SPRITE, `<svg xmlns="http://www.w3.org/2000/svg">\n${
  icons.map((i) => `<symbol id="${i.name}" viewBox="${i.viewBox}">${i.body}</symbol>`).join('\n')}\n</svg>\n`);

writeFileSync(NAMES, `// GENERATED by scripts/generate-icons.mjs from src/icons/ — do not edit.
// The NAMES only: each drawing is a symbol in icons.svg. TRAP T-an-icon-loads-when-first-drawn
//
// Map:
// - ICON_NAMES — every icon the set holds, by name

/** Every icon the set holds, by name. */
export const ICON_NAMES: ReadonlySet<string> = new Set([
${icons.map((i) => `  '${i.name}',`).join('\n')}
]);
`);

console.log(`generate-icons: ${icons.length} icons → ${SPRITE} and ${NAMES}`);
