#!/usr/bin/env node
/**
 * check-mcp.mjs — the MCP's registrations are its one statement. Each module in
 * `MODULES` lists in its header exactly what it registers, every tool and
 * argument says what it is, and `mcp-server/README.md` is what the
 * registrations write now. A README written by hand once listed 19 tools that
 * never existed.
 *
 *   npm run check:mcp               check
 *   npm run check:mcp -- --write    write the README, then check
 *
 * Map:
 * - registrations — what each module registers, caught by a server that only records
 * - readme — the README the registrations write
 */
import { globSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const MCP = join(dirname(fileURLToPath(import.meta.url)), '..', 'mcp-server');
const README = join(MCP, 'README.md');

/** The first block comment: its title line, and each name its indented list promises. */
function header(file) {
  const text = readFileSync(join(MCP, file), 'utf8');
  const block = text.slice(text.indexOf('/*'), text.indexOf('*/'));
  const lines = block.split('\n').slice(1);
  return {
    title: lines[0].replace(/^\s*\*\s*/, '').replace(/^[\w.-]+ — /, '').replace(/\.$/, '').replace(/^./, (c) => c.toUpperCase()),
    names: lines.map((l) => l.match(/^ \* {3}(\S+) {2,}\S/)?.[1]).filter(Boolean),
  };
}

/** What each module registers, caught by a server that only records. */
export async function registrations() {
  const { MODULES } = await import(pathToFileURL(join(MCP, 'server.js')).href);
  return Object.entries(MODULES).map(([file, mod]) => {
    const found = [];
    mod.register({
      registerTool: (name, config) => found.push({ kind: 'tool', name, config }),
      registerResource: (_name, uri, config) => found.push({ kind: 'resource', name: String(uri.uriTemplate ?? uri), config }),
      registerPrompt: (name, config) => found.push({ kind: 'prompt', name, config }),
    });
    return { file, ...header(file), found };
  });
}

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|');
const args = (shape) => Object.entries(shape ?? {});
const plural = (n, word) => `${n} ${word}${n === 1 ? '' : 's'}`;

/** The README the registrations write. */
export function readme(modules) {
  const of = (kind) => modules.map((m) => ({ ...m, found: m.found.filter((r) => r.kind === kind) })).filter((m) => m.found.length);
  const count = (kind) => of(kind).reduce((n, m) => n + m.found.length, 0);
  const out = [
    '# Sherpa UI — MCP server',
    '',
    '<!-- GENERATED by scripts/check-mcp.mjs from the server\'s registrations. Do not edit it: npm run check:mcp -- --write -->',
    '',
    'An MCP server for Sherpa UI, for an AI agent. It reads the `sherpa-ui` installed',
    'beside it — its specs, schemas, docs and tokens — and runs its own checks, its',
    'data layer and its usage check, never a copy of them. Each tool, resource and',
    'prompt below is written from the code that registers it.',
    '',
    `**${plural(count('tool'), 'tool')} · ${plural(count('resource'), 'resource')} · ${plural(count('prompt'), 'prompt')}.**`,
    '',
    '## Setup',
    '',
    'Node 22 or later. It is its own package, `sherpa-ui-mcp`, not on npm yet. An app',
    'made by `npm create sherpa-ui` has it: its `.mcp.json` starts',
    '`node node_modules/sherpa-ui-mcp/index.js`. In a sherpa-ui checkout, `npm run mcp`',
    'runs it against the checkout. Any other client gives `node` and the full path:',
    '',
    '```json',
    '{ "mcpServers": { "sherpa-ui": { "command": "node", "args": ["/full/path/to/sherpa-ui/mcp-server/index.js"] } } }',
    '```',
    '',
    'Do not use `npx sherpa-mcp`. On npm, `sherpa-mcp` is another author\'s package, and',
    'a client with no terminal installs a missing one without asking.',
    '',
    '## Tools',
  ];
  for (const m of of('tool')) {
    out.push('', `### ${m.title} · \`${m.file}\``);
    for (const { name, config } of m.found) {
      out.push('', `#### \`${name}\` — ${config.title}`, '', config.description);
      const list = args(config.inputSchema);
      if (list.length) out.push('', ...list.map(([key, s]) => `- \`${key}\`${s.isOptional() ? ' (optional)' : ''} — ${s.description}`));
    }
  }
  out.push('', '## Resources');
  for (const m of of('resource')) {
    out.push('', `### ${m.title} · \`${m.file}\``, '', '| URI | Is |', '|---|---|');
    for (const { name, config } of m.found) out.push(`| \`${name}\` | **${cell(config.title)}.** ${cell(config.description)} |`);
  }
  out.push('', '## Prompts', '');
  if (!count('prompt')) out.push('None yet.');
  for (const m of of('prompt')) {
    out.push(`### ${m.title} · \`${m.file}\``, '');
    for (const { name, config } of m.found) out.push(`- \`${name}\` — ${config.description}`);
  }
  out.push('', '## Adding to it', '',
    'A module registers its tools, resources or prompts and lists each in its header;',
    '`MODULES` in `server.js` names the module. `npm run check:mcp -- --write` then',
    'writes this file, and `npm run check:mcp` fails while it is stale.', '');
  return out.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const modules = await registrations();
  const problems = [];
  const listed = new Set(modules.map((m) => m.file));
  for (const file of globSync('{tools,resources,prompts}/*.js', { cwd: MCP })) {
    if (!listed.has(file)) problems.push(`mcp-server/${file} is in no entry of MODULES in server.js`);
  }
  for (const m of modules) {
    const real = m.found.map((r) => r.name);
    for (const n of m.names.filter((x) => !real.includes(x))) problems.push(`mcp-server/${m.file}: its header lists "${n}", which it does not register`);
    for (const n of real.filter((x) => !m.names.includes(x))) problems.push(`mcp-server/${m.file}: registers "${n}", which its header does not list`);
    for (const { kind, name, config } of m.found) {
      if (!config.title || !config.description) problems.push(`mcp-server/${m.file}: ${kind} ${name} needs a title and a description`);
      for (const [key, s] of args(config.inputSchema)) if (!s.description) problems.push(`mcp-server/${m.file}: ${name}'s \`${key}\` says nothing of what it is`);
    }
  }
  const text = readme(modules);
  if (process.argv.includes('--write')) writeFileSync(README, text);
  else if (readFileSync(README, 'utf8') !== text) problems.push(`${relative(process.cwd(), README)} is stale — npm run check:mcp -- --write`);
  if (problems.length) {
    for (const p of problems) console.error(`  ✗ ${p}`);
    console.error(`\ncheck-mcp: ${problems.length} problem(s). The registrations are the MCP's one statement: its headers and README follow them.`);
    process.exit(1);
  }
  const all = modules.flatMap((m) => m.found);
  console.log(`check-mcp: ${modules.length} modules, ${all.length} registrations; headers match and the README is fresh`);
}
